#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Test and verify no-review workflow setup
    
.DESCRIPTION
    Verifies that:
    - Pre-push hooks are installed
    - GitHub Actions workflows exist
    - Branch protection can be configured
    - All tests pass locally
#>

Write-Host ""
Write-Host "???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????" -ForegroundColor Yellow
Write-Host "  No-Review Workflow Setup Verification" -ForegroundColor Yellow
Write-Host "???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????" -ForegroundColor Yellow
Write-Host ""

$errors = 0
$warnings = 0

# Check Backend Repository
Write-Host "???? Backend Repository (userManagementApi)" -ForegroundColor Cyan
Write-Host ""

if (Test-Path "C:\Development\git\userManagementApi\.git\hooks\pre-push") {
    Write-Host "   ??? Pre-push hook installed" -ForegroundColor Green
} else {
    Write-Host "   ??? Pre-push hook missing!" -ForegroundColor Red
    $errors++
}

if (Test-Path "C:\Development\git\userManagementApi\.github\workflows\test.yml") {
    Write-Host "   ??? GitHub Actions test workflow exists" -ForegroundColor Green
} else {
    Write-Host "   ??? Test workflow missing!" -ForegroundColor Red
    $errors++
}

Write-Host ""

# Check Frontend Repository
Write-Host "???? Frontend Repository (fincore_WebUI)" -ForegroundColor Cyan
Write-Host ""

if (Test-Path "C:\Development\git\fincore_WebUI\.git\hooks\pre-push") {
    Write-Host "   ??? Pre-push hook installed" -ForegroundColor Green
} else {
    Write-Host "   ??? Pre-push hook missing!" -ForegroundColor Red
    $errors++
}

if (Test-Path "C:\Development\git\fincore_WebUI\.github\workflows\test-pr.yml") {
    Write-Host "   ??? GitHub Actions test workflow exists" -ForegroundColor Green
} else {
    Write-Host "   ??? Test workflow missing!" -ForegroundColor Red
    $errors++
}

Write-Host ""

# Test Backend Build
Write-Host "???? Testing Backend..." -ForegroundColor Cyan
Write-Host "   Running Maven tests (this may take a minute)..." -ForegroundColor Gray

Push-Location "C:\Development\git\userManagementApi"
$mvnOutput = mvn test -q 2>&1 | Out-String
$mvnExit = $LASTEXITCODE
Pop-Location

if ($mvnExit -eq 0) {
    $testCount = ([regex]::Match($mvnOutput, "Tests run: (\d+)")).Groups[1].Value
    Write-Host "   [OK] Backend tests passed ($testCount tests)" -ForegroundColor Green
} else {
    Write-Host "   [FAIL] Backend tests FAILED!" -ForegroundColor Red
    $errors++
}

Write-Host ""

# Check Branch Protection
Write-Host "???? Branch Protection Status" -ForegroundColor Cyan
Write-Host ""

if ($env:GITHUB_TOKEN) {
    Write-Host "   ??? GITHUB_TOKEN environment variable set" -ForegroundColor Green
    Write-Host "   ??????  Ready to configure branch protection" -ForegroundColor Yellow
    $warnings++
} else {
    Write-Host "   ??????  GITHUB_TOKEN not set" -ForegroundColor Yellow
    Write-Host "   ??????  Branch protection must be configured manually" -ForegroundColor Gray
    $warnings++
}

Write-Host ""

# Summary
Write-Host "???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????" -ForegroundColor Yellow
Write-Host ""

if ($errors -eq 0 -and $warnings -eq 0) {
    Write-Host "??? Setup complete! Everything is ready." -ForegroundColor Green
    Write-Host ""
    Write-Host "Next steps:" -ForegroundColor Cyan
    Write-Host "1. Configure branch protection on GitHub (see NO_REVIEW_WORKFLOW.md)" -ForegroundColor White
    Write-Host "2. Test by pushing your current PR" -ForegroundColor White
    Write-Host "3. PR will auto-merge when tests pass" -ForegroundColor White
} elseif ($errors -eq 0) {
    Write-Host "??????  Setup mostly complete with $warnings warnings" -ForegroundColor Yellow
    Write-Host ""
    Write-Host "Next steps:" -ForegroundColor Cyan
    Write-Host "1. Configure branch protection (see NO_REVIEW_WORKFLOW.md)" -ForegroundColor White
    Write-Host "2. Test the workflow" -ForegroundColor White
} else {
    Write-Host "??? Setup incomplete: $errors errors, $warnings warnings" -ForegroundColor Red
    Write-Host ""
    Write-Host "Please fix the errors above before proceeding." -ForegroundColor Yellow
}

Write-Host ""
Write-Host "Full documentation: NO_REVIEW_WORKFLOW.md" -ForegroundColor Gray
Write-Host ""
